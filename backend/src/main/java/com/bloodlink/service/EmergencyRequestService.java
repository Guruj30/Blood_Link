package com.bloodlink.service;

import com.bloodlink.dto.EmergencyRequestCreateDto;
import com.bloodlink.dto.EmergencyRequestResponseDto;
import com.bloodlink.dto.EmergencyRequestStatusUpdateDto;
import com.bloodlink.exception.InvalidBloodGroupException;
import com.bloodlink.exception.InvalidOperationException;
import com.bloodlink.exception.ResourceNotFoundException;
import com.bloodlink.model.BloodGroup;
import com.bloodlink.model.EmergencyRequest;
import com.bloodlink.model.RequestStatus;
import com.bloodlink.model.UrgencyLevel;
import com.bloodlink.repository.EmergencyRequestRepository;
import org.springframework.stereotype.Service;

import java.time.LocalDateTime;
import java.util.Collections;
import java.util.List;
import java.util.stream.Collectors;

/**
 * Service managing emergency requests, clinical prioritization, and status lifecycle.
 */
@Service
public class EmergencyRequestService {

    private final EmergencyRequestRepository requestRepository;
    private final BloodInventoryService inventoryService;
    private final CompatibilityRuleEngine compatibilityEngine;

    public EmergencyRequestService(EmergencyRequestRepository requestRepository,
                                  BloodInventoryService inventoryService,
                                  CompatibilityRuleEngine compatibilityEngine) {
        this.requestRepository = requestRepository;
        this.inventoryService = inventoryService;
        this.compatibilityEngine = compatibilityEngine;
    }

    /**
     * Lists emergency requests with deterministic clinical priority ordering:
     * Critical > High > Normal > Low, then earlier submission time, then ID tie-break.
     */
    public List<EmergencyRequestResponseDto> getAllRequests(String statusStr, String urgencyStr, String bloodGroupStr, String search) {
        RequestStatus filterStatus = null;
        if (statusStr != null && !statusStr.trim().isEmpty() && !"all".equalsIgnoreCase(statusStr)) {
            filterStatus = RequestStatus.fromValue(statusStr);
        }

        UrgencyLevel filterUrgency = null;
        if (urgencyStr != null && !urgencyStr.trim().isEmpty() && !"all".equalsIgnoreCase(urgencyStr)) {
            filterUrgency = UrgencyLevel.fromValue(urgencyStr);
        }

        BloodGroup filterBg = null;
        if (bloodGroupStr != null && !bloodGroupStr.trim().isEmpty() && !"all".equalsIgnoreCase(bloodGroupStr)) {
            try {
                filterBg = BloodGroup.fromCode(bloodGroupStr);
            } catch (IllegalArgumentException e) {
                throw new InvalidBloodGroupException(bloodGroupStr);
            }
        }

        final RequestStatus finalStatus = filterStatus;
        final UrgencyLevel finalUrgency = filterUrgency;
        final BloodGroup finalBg = filterBg;
        final String finalSearch = (search != null) ? search.trim().toLowerCase() : null;

        return requestRepository.findAll().stream()
                .filter(r -> finalStatus == null || r.getStatus() == finalStatus)
                .filter(r -> finalUrgency == null || r.getUrgency() == finalUrgency)
                .filter(r -> finalBg == null || r.getBloodGroup() == finalBg)
                .filter(r -> finalSearch == null || finalSearch.isEmpty() ||
                        r.getId().toLowerCase().contains(finalSearch) ||
                        r.getHospital().toLowerCase().contains(finalSearch) ||
                        r.getLocation().toLowerCase().contains(finalSearch))
                .sorted() // Uses EmergencyRequest.compareTo for deterministic priority ordering
                .map(this::toDto)
                .collect(Collectors.toList());
    }

    public EmergencyRequestResponseDto getRequestById(String id) {
        EmergencyRequest request = requestRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Emergency Request", id));
        return toDto(request);
    }

    public EmergencyRequestResponseDto createRequest(EmergencyRequestCreateDto dto) {
        BloodGroup bg;
        try {
            bg = BloodGroup.fromCode(dto.getBloodGroup());
        } catch (IllegalArgumentException e) {
            throw new InvalidBloodGroupException(dto.getBloodGroup());
        }

        UrgencyLevel urgency = UrgencyLevel.fromValue(dto.getUrgency());

        EmergencyRequest request = new EmergencyRequest(
                null, // will be generated by repository (REQ-nextNum)
                bg,
                dto.getUnits(),
                dto.getHospital(),
                dto.getLocation(),
                urgency,
                RequestStatus.PENDING,
                LocalDateTime.now(),
                dto.getNotes(),
                dto.getRequester()
        );

        EmergencyRequest saved = requestRepository.save(request);
        return toDto(saved);
    }

    /**
     * Updates status in the clinical lifecycle pipeline.
     * Prevents duplicate inventory deductions when transitioning to FULFILLED.
     */
    public synchronized EmergencyRequestResponseDto updateRequestStatus(String id, EmergencyRequestStatusUpdateDto dto) {
        EmergencyRequest request = requestRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Emergency Request", id));

        RequestStatus newStatus = RequestStatus.fromValue(dto.getStatus());
        RequestStatus oldStatus = request.getStatus();

        if (oldStatus == RequestStatus.FULFILLED && newStatus == RequestStatus.FULFILLED) {
            throw new InvalidOperationException("Request " + id + " has already been fulfilled. Duplicate fulfillment is prevented.");
        }

        if (oldStatus == RequestStatus.CANCELLED && newStatus != RequestStatus.CANCELLED) {
            throw new InvalidOperationException("Cancelled request " + id + " cannot be reopened.");
        }

        // When fulfilling an active request, perform safety stock verification and atomic deduction
        if (newStatus == RequestStatus.FULFILLED && oldStatus != RequestStatus.FULFILLED) {
            if (dto.isDeductInventoryOnFulfillment()) {
                inventoryService.deductStock(request.getBloodGroup(), request.getUnits());
            }
        }

        request.setStatus(newStatus);
        if (dto.getNotes() != null && !dto.getNotes().trim().isEmpty()) {
            String updatedNotes = (request.getNotes() != null ? request.getNotes() + " | " : "") + dto.getNotes().trim();
            request.setNotes(updatedNotes);
        }

        EmergencyRequest saved = requestRepository.save(request);
        return toDto(saved);
    }

    public EmergencyRequestResponseDto toDto(EmergencyRequest req) {
        List<String> compatibleGroups = compatibilityEngine.getCompatibleDonorsForRecipient(req.getBloodGroup())
                .stream()
                .map(BloodGroup::getCode)
                .collect(Collectors.toList());

        int availableStock = inventoryService.getAvailableStock(req.getBloodGroup());
        boolean canFulfill = availableStock >= req.getUnits();

        return new EmergencyRequestResponseDto(
                req.getId(),
                req.getBloodGroup().getCode(),
                req.getUnits(),
                req.getHospital(),
                req.getLocation(),
                req.getUrgency().getValue(),
                req.getStatus().getValue(),
                req.getCreatedAt(),
                req.getNotes(),
                req.getRequester(),
                compatibleGroups,
                availableStock,
                canFulfill
        );
    }
}
