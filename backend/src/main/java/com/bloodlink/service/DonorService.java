package com.bloodlink.service;

import com.bloodlink.dto.DonorRequestDto;
import com.bloodlink.dto.DonorResponseDto;
import com.bloodlink.exception.InvalidBloodGroupException;
import com.bloodlink.exception.ResourceNotFoundException;
import com.bloodlink.model.AvailabilityStatus;
import com.bloodlink.model.BloodGroup;
import com.bloodlink.model.Donor;
import com.bloodlink.repository.DonorRepository;
import org.springframework.stereotype.Service;

import java.time.LocalDate;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Collectors;

/**
 * Business service managing blood donor registry operations.
 */
@Service
public class DonorService {

    private final DonorRepository donorRepository;
    private final DonorEligibilityService eligibilityService;
    private final CompatibilityRuleEngine compatibilityEngine;

    public DonorService(DonorRepository donorRepository,
                        DonorEligibilityService eligibilityService,
                        CompatibilityRuleEngine compatibilityEngine) {
        this.donorRepository = donorRepository;
        this.eligibilityService = eligibilityService;
        this.compatibilityEngine = compatibilityEngine;
    }

    public List<DonorResponseDto> getAllDonors(String bloodGroupStr, String city, String availabilityStr, String search) {
        BloodGroup filterBg = null;
        if (bloodGroupStr != null && !bloodGroupStr.trim().isEmpty() && !"all".equalsIgnoreCase(bloodGroupStr)) {
            try {
                filterBg = BloodGroup.fromCode(bloodGroupStr);
            } catch (IllegalArgumentException e) {
                throw new InvalidBloodGroupException(bloodGroupStr);
            }
        }

        AvailabilityStatus filterAvail = null;
        if (availabilityStr != null && !availabilityStr.trim().isEmpty() && !"all".equalsIgnoreCase(availabilityStr)) {
            filterAvail = AvailabilityStatus.fromValue(availabilityStr);
        }

        final BloodGroup finalBg = filterBg;
        final AvailabilityStatus finalAvail = filterAvail;
        final String finalSearch = (search != null) ? search.trim().toLowerCase() : null;
        final String finalCity = (city != null && !"all".equalsIgnoreCase(city.trim())) ? city.trim().toLowerCase() : null;

        return donorRepository.findAll().stream()
                .filter(d -> finalBg == null || d.getBloodGroup() == finalBg)
                .filter(d -> finalAvail == null || d.getAvailability() == finalAvail)
                .filter(d -> finalCity == null || d.getCity().toLowerCase().contains(finalCity))
                .filter(d -> finalSearch == null || finalSearch.isEmpty() ||
                        d.getName().toLowerCase().contains(finalSearch) ||
                        d.getId().toLowerCase().contains(finalSearch) ||
                        d.getCity().toLowerCase().contains(finalSearch))
                .sorted(Comparator.comparing(Donor::getName))
                .map(this::toDto)
                .collect(Collectors.toList());
    }

    public DonorResponseDto getDonorById(String id) {
        Donor donor = donorRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Donor", id));
        return toDto(donor);
    }

    public DonorResponseDto registerDonor(DonorRequestDto dto) {
        BloodGroup bg;
        try {
            bg = BloodGroup.fromCode(dto.getBloodGroup());
        } catch (IllegalArgumentException e) {
            throw new InvalidBloodGroupException(dto.getBloodGroup());
        }

        AvailabilityStatus avail = AvailabilityStatus.fromValue(dto.getAvailability());
        LocalDate eligibleAfter = eligibilityService.calculateEligibleAfterDate(dto.getLastDonation());

        Donor donor = new Donor(
                null, // will be generated by repository
                dto.getName(),
                bg,
                dto.getCity(),
                dto.getPhone(),
                avail,
                dto.getLastDonation(),
                eligibleAfter,
                LocalDate.now(),
                dto.getNotes() != null ? dto.getNotes() : "Registered via BloodLink API"
        );

        Donor saved = donorRepository.save(donor);
        return toDto(saved);
    }

    public DonorResponseDto updateDonor(String id, DonorRequestDto dto) {
        Donor existing = donorRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Donor", id));

        BloodGroup bg;
        try {
            bg = BloodGroup.fromCode(dto.getBloodGroup());
        } catch (IllegalArgumentException e) {
            throw new InvalidBloodGroupException(dto.getBloodGroup());
        }

        existing.setName(dto.getName());
        existing.setBloodGroup(bg);
        existing.setCity(dto.getCity());
        existing.setPhone(dto.getPhone());
        existing.setAvailability(AvailabilityStatus.fromValue(dto.getAvailability()));
        existing.setLastDonation(dto.getLastDonation());
        existing.setEligibleAfter(eligibilityService.calculateEligibleAfterDate(dto.getLastDonation()));
        if (dto.getNotes() != null) {
            existing.setNotes(dto.getNotes());
        }

        Donor saved = donorRepository.save(existing);
        return toDto(saved);
    }

    public void deleteDonor(String id) {
        boolean removed = donorRepository.deleteById(id);
        if (!removed) {
            throw new ResourceNotFoundException("Donor", id);
        }
    }

    /**
     * Finds donors compatible with a recipient's blood group using immunological rules.
     */
    public List<DonorResponseDto> findCompatibleDonors(String recipientBgStr, String city, boolean availableOnly) {
        BloodGroup recipientBg;
        try {
            recipientBg = BloodGroup.fromCode(recipientBgStr);
        } catch (IllegalArgumentException e) {
            throw new InvalidBloodGroupException(recipientBgStr);
        }

        List<BloodGroup> compatibleGroups = compatibilityEngine.getCompatibleDonorsForRecipient(recipientBg);
        final String finalCity = (city != null && !"all".equalsIgnoreCase(city.trim())) ? city.trim().toLowerCase() : null;

        return donorRepository.findAll().stream()
                .filter(d -> compatibleGroups.contains(d.getBloodGroup()))
                .filter(d -> !availableOnly || d.getAvailability() == AvailabilityStatus.AVAILABLE)
                .filter(d -> finalCity == null || d.getCity().toLowerCase().contains(finalCity))
                .map(this::toDto)
                .collect(Collectors.toList());
    }

    public DonorResponseDto toDto(Donor donor) {
        LocalDate today = LocalDate.now();
        boolean intervalSatisfied = eligibilityService.isDonorEligible(donor, today);
        long daysRemaining = eligibilityService.getDaysRemaining(donor.getLastDonation(), today);

        return new DonorResponseDto(
                donor.getId(),
                donor.getName(),
                donor.getBloodGroup().getCode(),
                donor.getCity(),
                donor.getPhone(),
                donor.getAvailability().getValue(),
                donor.getLastDonation(),
                donor.getEligibleAfter(),
                donor.getRegistered(),
                donor.getNotes(),
                intervalSatisfied && donor.getAvailability() == AvailabilityStatus.AVAILABLE,
                daysRemaining
        );
    }
}
